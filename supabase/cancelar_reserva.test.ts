import { readFileSync } from "node:fs";
import { PGlite } from "@electric-sql/pglite";
import { afterAll, beforeAll, beforeEach, describe, expect, it } from "vitest";

let db: PGlite;
const esquema = `
  create role anon; create role authenticated;
  create table public.usuarios (id bigint primary key);
  create table public.recursos (id bigint primary key);
  create table public.franjas (id bigint primary key, recurso_id bigint references public.recursos);
  create table public.reservas (
    id bigint generated by default as identity primary key,
    franja_id bigint references public.franjas, recurso_id bigint references public.recursos,
    usuario_id bigint references public.usuarios, fecha date, hora_inicio time,
    hora_fin time, estado text, creada_en timestamptz default now()
  );
  insert into public.usuarios values (7), (8);
  insert into public.recursos values (2);
  insert into public.franjas values (15, 2), (16, 2);
`;
const insertar = (usuario = 7, franja = 15, estado = "activa") => db.query(
  `insert into public.reservas(franja_id,recurso_id,usuario_id,fecha,hora_inicio,hora_fin,estado)
   values ($1,2,$2,'2099-11-01','10:00','11:00',$3) returning *`, [franja, usuario, estado]);

beforeAll(async () => {
  db = new PGlite();
  await db.exec(esquema);
  await db.exec(readFileSync(new URL("./integridad_reservas.sql", import.meta.url), "utf8"));
  await db.exec(readFileSync(new URL("./cancelar_reserva.sql", import.meta.url), "utf8"));
});
beforeEach(async () => { await db.exec("truncate public.reservas restart identity;"); });
afterAll(async () => { await db.close(); });

describe("Reglas PostgreSQL de cancelación del prototipo", () => {
  it("verifica que la reserva sea del estudiante indicado", async () => {
    await insertar();
    await expect(db.query("select * from public.cancelar_reserva(1,8)")).rejects.toThrow("RESERVA_NO_CANCELABLE");
    const { rows } = await db.query<{ estado: string }>("select estado from public.reservas where id=1");
    expect(rows[0]?.estado).toBe("activa");
  });

  it("solo cambia el estado de la reserva elegida, conservando las demás y el historial", async () => {
    await insertar(); await insertar(8, 16);
    const antes = await db.query("select * from public.reservas order by id");
    await db.query("select * from public.cancelar_reserva(1,7)");
    const despues = await db.query("select * from public.reservas order by id");
    expect(despues.rows).toEqual([{ ...antes.rows[0], estado: "cancelada" }, antes.rows[1]]);
  });

  it("libera la franja cancelada para otro estudiante", async () => {
    await insertar();
    await db.query("select * from public.cancelar_reserva(1,7)");
    await insertar(8, 15);
    const { rows } = await db.query<{ usuario_id: number }>("select usuario_id from public.reservas where franja_id=15 and estado='activa'");
    expect(rows).toEqual([{ usuario_id: 8 }]);
  });

  it("permite al estudiante hacer una nueva reserva después de cancelar", async () => {
    await insertar();
    await db.query("select * from public.cancelar_reserva(1,7)");
    await insertar(7, 16);
    const { rows } = await db.query("select franja_id from public.reservas where usuario_id=7 and estado='activa'");
    expect(rows).toEqual([{ franja_id: 16 }]);
  });

  it("impide dos reservas activas vigentes del mismo estudiante", async () => {
    await insertar();
    await expect(insertar(7, 16)).rejects.toThrow("ESTUDIANTE_CON_RESERVA_ACTIVA");
  });

  it("impide dos reservas activas de una misma franja", async () => {
    await insertar();
    await expect(insertar(8, 15)).rejects.toThrow();
    const { rows } = await db.query<{ total: number }>("select count(*)::integer as total from public.reservas where franja_id=15 and estado='activa'");
    expect(rows[0]?.total).toBe(1);
  });

  it("las completadas no bloquean otra reserva ni se pueden cancelar", async () => {
    await insertar(7, 15, "completada");
    await expect(db.query("select * from public.cancelar_reserva(1,7)")).rejects.toThrow("RESERVA_NO_CANCELABLE");
    await insertar(7, 16);
    const { rows } = await db.query("select estado from public.reservas order by id");
    expect(rows).toEqual([{ estado: "completada" }, { estado: "activa" }]);
  });

  it("una repetición de cancelar es idempotente", async () => {
    await insertar();
    const primera = await db.query("select * from public.cancelar_reserva(1,7)");
    const segunda = await db.query("select * from public.cancelar_reserva(1,7)");
    expect(segunda.rows).toEqual(primera.rows);
  });

  it("la función no concede actualización general a anon", async () => {
    const { rows } = await db.query<{ actualiza: boolean; cancela: boolean }>(
      `select has_table_privilege('anon','public.reservas','UPDATE') as actualiza,
      has_function_privilege('anon','public.cancelar_reserva(bigint,bigint)','EXECUTE') as cancela`);
    expect(rows).toEqual([{ actualiza: false, cancela: true }]);
  });
});